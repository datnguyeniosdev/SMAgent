"""Render docs/evidence/demo_results.json (written by scripts.demo) as docs/DEMO_EVIDENCE.md."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def steps_table(ev: dict) -> list[str]:
    out = [
        "| step | state | attempts | executor | duration s | error |",
        "|---|---|---|---|---|---|",
    ]
    for s in ev.get("steps", []):
        err = (s.get("error") or "").replace("|", "/")[:90]
        out.append(
            f"| {s['step']} | {s['state']} | {s['attempts']} | {s.get('executor') or ''} | {s.get('duration_s')} | {err} |"
        )
    return out


def block(title: str, ev: dict, keys: list[str]) -> list[str]:
    md = [
        f"### {title}",
        "",
        f"- task `{ev['task_id']}` → **{ev['state']}**"
        + (f" (`{ev['error_category']}`: {ev['error'][:160]})" if ev.get("error") else ""),
        f"- routing: {ev.get('routing', {}).get('mode')} → {ev.get('domain')}/{ev.get('operation')}",
    ]
    for k in keys:
        if k in ev:
            md.append(f"- {k}: `{json.dumps(ev[k], default=str)[:400]}`")
    if ev.get("validations"):
        md.append(
            f"- validators: {', '.join(v['id'] + '=' + v['status'] for v in ev['validations'])}"
        )
    if ev.get("artifacts"):
        md.append(
            "- artifacts: "
            + ", ".join(
                f"{a['file']} ({a['kind']}, sha256 {a['sha256']}…, {a['validation']})"
                for a in ev["artifacts"]
            )
        )
    return md + [""] + steps_table(ev) + [""]


def main():
    r = json.loads((ROOT / "docs/evidence/demo_results.json").read_text())
    md = [
        "# Demonstration Evidence",
        "",
        "Generated by `uv run python -m scripts.demo --unity-project <path>` then `uv run python -m scripts.render_evidence`.",
        "Every row below is a real execution through the gateway (TaskRequest → planner → engine → tools/plugins → validators).",
        "No model, agent or image provider was available, so those paths show their real failure/unsupported results.",
        "",
        "## Environment at run time",
        "",
        "| capability | status |",
        "|---|---|",
    ]
    md += [f"| {k} | {v} |" for k, v in r["environment"]["capabilities"].items()]
    md += [
        "",
        f"Tools registered: {len(r['environment']['tools'])} — "
        + ", ".join(f"`{t}`" for t in r["environment"]["tools"]),
        "",
    ]
    md += ["## Phase 4 — workflow engine", ""]
    md += block(
        "A. Sequential (output of step N feeds step N+1)", r["P4-A sequential"], ["output_csv"]
    )
    md += block(
        "B. Parallel + dependent aggregation",
        r["P4-B parallel"],
        ["overlapped", "aggregate_waited"],
    )
    md += block(
        "C1. Bounded retry of an idempotent real MCP tool",
        r["P4-C1 retry (idempotent, real MCP)"],
        [],
    )
    md += block(
        "C2. Failure policy: non-idempotent not retried, independent branch continues",
        r["P4-C2 failure policy"],
        [],
    )
    md += block(
        "D. Cancellation of a running subprocess",
        r["P4-D cancellation"],
        ["cancel_latency_s", "sleep_processes_left"],
    )
    md += block(
        "E. Approval checkpoint",
        r["P4-E approval"],
        [
            "state_while_waiting",
            "file_existed_before_approval",
            "file_exists_after",
            "approval_record",
            "main_checkout_untouched",
        ],
    )
    f = r["P4-F recovery"]
    md += [
        "### F. Crash + restart recovery (real process killed with os._exit)",
        "",
        f"- crash exit code {f['crash_exit_code']}, restart exit code {f['recover_exit_code']}",
        f"- recovery actions: `{json.dumps(f['recovery_actions'])}`",
        f"- tasks after restart: `{json.dumps(f['tasks_after_restart'])}`",
        f"- side-effect log after restart: `{f['side_effect_log'].strip()}` (written once — not replayed)",
        f"- idempotent step executions: {f['idempotent_runs']} (interrupted run + resumed run)",
        "",
    ]
    md += block(
        "G. Multi-agent (implement → QA → independent review)",
        r["P4-G multi-agent"],
        ["agent_capability"],
    )
    md += ["## Phase 5 — domain plugins", ""]
    md += block(
        "A. Software: create files in isolated worktree, run real pytest, change report",
        r["P5-A software"],
        ["main_checkout_untouched"],
    )
    md += block(
        "B. Research/documents: extract facts with provenance, cited report",
        r["P5-B research/documents"],
        [],
    )
    md += [
        "<details><summary>report excerpt</summary>",
        "",
        "```markdown",
        r["P5-B research/documents"]["report_excerpt"],
        "```",
        "</details>",
        "",
    ]
    md += block(
        "C. Data: aggregate CSV, validate, export, summarize", r["P5-C data"], ["output_csv"]
    )
    md += block("D1. Media: inspect a real PNG", r["P5-D media"]["inspect"], [])
    md += block("D2. Media: generate (no provider configured)", r["P5-D media"]["generate"], [])
    md += block("E. Cross-domain: document report + data profile", r["P5-E cross-domain"], [])
    for name, ev in r["P5-F unity"].items():
        if isinstance(ev, dict):
            md += block(f"F. Unity: {name}", ev, ["project"])
    md += [
        "## Notifications sent (sample, via the notifier interface)",
        "",
        "```",
        *r["notifications_sample"],
        "```",
        "",
    ]
    (ROOT / "docs/DEMO_EVIDENCE.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
